// Tests conversations par projet, notes de tâches, tâches éphémères. Usage : node test/conversations-test.js
const fs = require('fs'), os = require('os'), path = require('path');
process.env.NOESIS_DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'conv-'));
let failed = 0;
const assert = (c, l) => { if (c) console.log('  ok  ' + l); else { failed++; console.log('  FAIL ' + l); } };
const throwsStatus = (fn) => { try { fn(); return 0; } catch (e) { return e.statusCode || -1; } };
const db = require('../server/db');
const conv = require('../server/lib/conversations');
const goalstasks = require('../server/lib/goalstasks');
const now = new Date().toISOString();
['u1', 'u2', 'u3'].forEach((id) => db.prepare("INSERT INTO users (id, name, color, createdAt) VALUES (?, ?, '#674EA7', ?)").run(id, id, now));
const act = Number(db.prepare("INSERT INTO activities (name, ownerId, createdAt) VALUES ('P', 'u1', ?)").run(now).lastInsertRowid);
const solo = Number(db.prepare("INSERT INTO activities (name, ownerId, createdAt) VALUES ('S', 'u1', ?)").run(now).lastInsertRowid);
const mem = (a, u) => db.prepare("INSERT INTO activity_members (activityId, userId, color, joinedAt) VALUES (?, ?, '#674EA7', ?)").run(a, u, now);
mem(act, 'u1'); mem(act, 'u2'); mem(solo, 'u1');
assert(throwsStatus(() => conv.listConversations('u3', act)) === 403, 'non-membre refusé');
assert(throwsStatus(() => conv.listConversations('u1', solo)) === 400, 'projet solo : pas de conversations');
for (let i = 1; i <= 8; i++) conv.createGroupConversation('u1', act, 'Conv ' + i);
const d1 = conv.openDirectConversation('u1', act, 'u2'), d2 = conv.openDirectConversation('u2', act, 'u1');
assert(d1.id === d2.id && d2.existing, 'un seul message individuel par paire, hors limite de 9');
assert(throwsStatus(() => conv.openDirectConversation('u1', act, 'u3')) === 400, 'destinataire non membre refusé');
conv.postMessage('u1', d1.id, 'salut');
assert(conv.unreadByActivity('u2')[act] === 1 && !conv.unreadByActivity('u1')[act], 'non lus comptés pour le destinataire seulement');
assert(conv.messages('u2', d1.id, true).messages.length === 1 && !conv.unreadByActivity('u2')[act], 'lecture remet à zéro');
db.prepare("INSERT INTO users (id, name, color, createdAt) VALUES ('u4', 'u4', '#674EA7', ?)").run(now); mem(act, 'u4');
assert(throwsStatus(() => conv.messages('u4', d1.id)) === 403, 'message individuel privé');
assert(conv.listConversations('u4', act).conversations.every((c) => c.kind === 'group'), 'liste : pas les privés des autres');
// tâches
const sp = require('../server/lib/subprojects');
const goals = require('../server/lib/goals');
const cat = { key: goals.addCategory(act, 'Pôle test')[0].key };
let task = goalstasks.addCategoryTask(act, 'u1', cat.key, 'Tâche A', {});
if (task) {
  const g = conv.createGroupConversation('u2', act, '', task.id);
  assert(!g.existing && conv.createGroupConversation('u1', act, '', task.id).existing, 'une conversation par tâche');
  assert(throwsStatus(() => conv.createGroupConversation('u2', act, 'Dixième')) === 409, 'limite de 9 conversations de groupe');
  for (let i = 1; i <= 4; i++) conv.addNote('u1', task.id, 'note ' + i);
  const l = conv.latestNotes('u2', act, 3);
  assert(l.length === 3 && l[0].body === 'note 4', 'trois dernières notes');
  assert(throwsStatus(() => conv.addNote('u3', task.id, 'x')) === 403, 'note : membre requis');
  conv.setEphemeral(task.id, 1);
  assert(conv.purgeExpired() === 0, 'éphémère non échue conservée');
  assert(conv.purgeExpired(new Date(Date.now() + 2 * 86400000)) === 1 && !conv.itemInfo(task.id), 'éphémère échue supprimée');
  const t2 = goalstasks.addCategoryTask(act, 'u1', cat.key, 'Tâche B', {});
  conv.setEphemeral(t2.id, 1);
  db.prepare('UPDATE sub_project_items SET done = 1, doneAt = ? WHERE id = ?').run(now, t2.id);
  assert(conv.purgeExpired(new Date(Date.now() + 2 * 86400000)) === 0 && conv.itemInfo(t2.id), 'éphémère déjà faite conservée');
  assert(throwsStatus(() => conv.addNote('u1', t2.id, 'x')) === 400, 'note refusée sur tâche faite');
} else console.log('  (pas de catégorie par défaut : tests de tâches ignorés)');
fs.rmSync(process.env.NOESIS_DATA_DIR, { recursive: true, force: true });
process.exit(failed ? 1 : 0);
