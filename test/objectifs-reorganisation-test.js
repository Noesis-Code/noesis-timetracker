// Réorganisation branchée (bloc 4 du schéma v46) : un nouvel objectif décale ceux qui le suivent, rien n'est écrit avant l'application, jamais un objectif à date fixée.
process.env.TZ = 'America/Montreal';
process.env.NOESIS_DATA_DIR = require('./lib/tmpdir').mkTmp('tmt-reorg-');
process.env.RAILWAY_ENVIRONMENT_NAME = 'staging';
let failed = 0;
const assert = (c, l) => { if (c) console.log('  ok  ' + l); else { failed++; console.log('  FAIL ' + l); } };
const db = require('../server/db');
const goals = require('../server/lib/goals');
const categories = require('../server/lib/categories');
const o = require('../server/lib/objectifs');
db.prepare("INSERT INTO users (id, name, createdAt) VALUES ('u1', 'u1', datetime('now'))").run();
const act = Number(db.prepare("INSERT INTO activities (name, ownerId, createdAt) VALUES ('Atelier', 'u1', '')").run().lastInsertRowid);
db.prepare("INSERT INTO activity_members (activityId, userId, color, joinedAt) VALUES (?, 'u1', '#fff', '')").run(act);
categories.addCategory(act, 'Production'); const poleKey = goals.categoriesForActivity(act)[0].key;
const mk = (title, start, end, extra) => o.creer('u1', Object.assign({ title, activityId: act, level: 'pole', poleKey, startDate: start, endDate: end }, extra || {}));
const row = (id) => db.prepare('SELECT startDate, endDate FROM user_objectives WHERE id = ?').get(id);
const a = mk('Suivant un', '2027-02-01', '2027-03-31');
const b = mk('Suivant deux', '2027-04-01', '2027-06-30');
const fixe = mk('Date fixée', '2027-09-01', '2027-10-31', { dateFixe: true });
const body = { activityId: act, level: 'pole', poleKey, endDate: '2027-02-28', dateFixe: true };
const p = o.reorganisation('u1', body);
assert(p.moves.length === 2 && p.moves[0].id === a.id && p.moves[0].apres.startDate === '2027-03-01', 'proposition : les deux objectifs qui suivent sont décalés après le nouvel (' + p.moves.length + ')');
assert(!p.moves.some((m) => m.id === fixe.id), 'l’objectif à date fixée n’est jamais déplacé');
assert(row(a.id).startDate === '2027-02-01', 'rien n’est écrit par la proposition');
const bad = o.appliquerReorganisation('u1', Object.assign({}, body, { moves: [{ id: a.id, startDate: '2027-05-05', endDate: '2027-06-01' }] }));
assert(bad.moved.length === 0 && row(a.id).startDate === '2027-02-01', 'un déplacement non proposé est refusé en silence');
const ok = o.appliquerReorganisation('u1', Object.assign({}, body, { moves: p.moves.map((m) => ({ id: m.id, startDate: m.apres.startDate, endDate: m.apres.endDate })) }));
assert(ok.moved.length === 2 && row(a.id).startDate === '2027-03-01' && row(b.id).startDate > row(a.id).endDate, 'application : les dates proposées sont écrites');
assert(o.reorganisation('u1', { activityId: act, level: 'pole', poleKey, endDate: 'nimporte quoi' }).moves.length === 0, 'entrée invalide : rien, aucune erreur');
console.log(failed ? '\nobjectifs-reorganisation-test : ' + failed + ' ÉCHEC(S)' : '\nobjectifs-reorganisation-test : OK');
process.exit(failed ? 1 : 0);
