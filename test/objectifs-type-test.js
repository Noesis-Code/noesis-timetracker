// Type d'une catégorie (projet / progression) : IA injectée, repli mots-clés, description vide, héritage, stockage et relecture. Usage : node test/objectifs-type-test.js
process.env.NOESIS_DATA_DIR = require('./lib/tmpdir').mkTmp('tmt-ot-');
process.env.RAILWAY_ENVIRONMENT_NAME = 'staging';
delete process.env.ANTHROPIC_API_KEY;
let failed = 0;
const assert = (c, l) => { if (c) console.log('  ok  ' + l); else { failed++; console.log('  FAIL ' + l); } };
const db = require('../server/db');
const T = require('../server/lib/objectifs-type');
(async () => {
  assert(T.lexical('Mon application', 'Construire et lancer une application mobile') === 'projet', 'mots-clés : application = projet');
  assert(T.lexical('Mariage', 'Organiser notre mariage en juin') === 'projet', 'mots-clés : événement = projet');
  assert(T.lexical('Course', 'Courir un marathon, progresser par paliers') === 'progression', 'mots-clés : course = progression');
  assert(T.lexical('Vie', 'Des choses diverses') === null, 'aucun mot : null');
  assert(T.sensDe('Tabac', 'Arrêter de fumer') === 'inverse' && T.sensDe('Course', 'Courir plus') === 'normal', 'sens inverse pour une diminution');
  const iaProjet = async () => ({ type: 'projet', sens: 'normal' });
  let r = await T.lire({ titre: 'X', description: '' }, { ia: iaProjet });
  assert(r.type === null && r.source === 'aucune', 'description vide : null sans appeler l’IA');
  r = await T.lire({ titre: 'X', description: 'Un livre à écrire' }, { ia: iaProjet });
  assert(r.type === 'projet' && r.source === 'ia' && r.sens === null, 'IA : projet');
  r = await T.lire({ titre: 'X', description: 'Perdre 5 kg' }, { ia: async () => ({ type: 'progression', sens: 'inverse' }) });
  assert(r.type === 'progression' && r.sens === 'inverse', 'IA : progression de sens inverse');
  r = await T.lire({ titre: 'X', description: 'Flou' }, { ia: async () => null });
  assert(r.type === null, 'IA dit ambigu : null, pas de repli');
  r = await T.lire({ titre: 'Course', description: 'Courir un semi-marathon' }, { ia: async () => { throw new Error('panne'); } });
  assert(r.type === 'progression' && r.source === 'mots-cles', 'IA en panne : repli mots-clés');
  r = await T.lire({ titre: 'Course', description: 'Courir un semi-marathon' }, { ia: async () => ({ type: 'bizarre' }) });
  assert(r.source === 'mots-cles', 'réponse invalide : repli mots-clés');
  r = await T.lire({ titre: 'Course', description: 'Courir un semi-marathon' });
  assert(r.type === 'progression' && r.source === 'mots-cles', 'sans clé API : repli mots-clés');
  assert(T.heriterPur([{ type: null }, { type: 'projet' }]).type === 'projet', 'héritage : le secteur reprend le pôle');
  assert(T.heriterPur([{ type: 'progression', sens: 'inverse' }, { type: 'projet' }]).sens === 'inverse', 'héritage : le propre prime');
  assert(T.heriterPur([{ type: null }, { type: null }]).type === null, 'héritage : rien -> null');
  const now = new Date().toISOString();
  db.exec('PRAGMA foreign_keys = OFF');
  const ins = db.prepare('INSERT INTO activity_goal_categories (activityId, key, label, color, position, createdAt, parentKey, description) VALUES (1, ?, ?, ?, 0, ?, ?, ?)');
  ins.run('pole', 'Mon app', '#fff', now, null, 'Construire une application');
  ins.run('sect', 'Divers', '#fff', now, 'pole', '');
  let calls = 0; const ia = async () => { calls++; return { type: 'projet', sens: 'normal' }; };
  let e = await T.typeEffectif(1, 'sect', { ia });
  assert(e.type === 'projet', 'secteur sans description hérite du pôle');
  const n1 = calls; await T.typeEffectif(1, 'sect', { ia });
  assert(calls === n1, 'lu une seule fois : mémorisé');
  db.prepare("UPDATE activity_goal_categories SET description = 'Courir un marathon' WHERE key = 'pole'").run();
  e = await T.typeEffectif(1, 'pole', { ia: async () => ({ type: 'progression', sens: 'normal' }) });
  assert(e.type === 'progression', 'description changée : relu');
  T.oublier(1, 'pole');
  assert(db.prepare("SELECT objectifTypeHash h FROM activity_goal_categories WHERE key='pole'").get().h === null, 'oublier efface l’empreinte');
  e = await T.typeEffectif(1, 'absente', { ia });
  assert(e.type === null, 'catégorie absente : null');
  process.exit(failed ? 1 : 0);
})();
