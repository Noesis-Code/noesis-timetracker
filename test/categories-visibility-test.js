// Pôles/secteurs supprimés ou renommés : listes du Chrono et de la Feuille de route.
// Usage : node test/categories-visibility-test.js
const os = require('os'); const fs = require('fs'); const path = require('path');
process.env.NOESIS_DATA_DIR = require('./lib/tmpdir').mkTmp('tmt-catvis-');
let failed = 0;
function assert(c, l) { if (c) console.log('  ok  ' + l); else { failed += 1; console.log('  FAIL ' + l); } }
const db = require('../server/db');
const goals = require('../server/lib/goals');
const now = new Date().toISOString();
db.prepare("INSERT INTO users (id, name, createdAt) VALUES ('u1', 'T', ?)").run(now);
const A = db.prepare("INSERT INTO activities (name, ownerId, createdAt) VALUES ('a', 'u1', ?)").run(now).lastInsertRowid;
const y = new Date().getFullYear();
goals.addCategory(A, 'Pole1'); goals.addCategory(A, 'Pole2');
const poles = goals.categoriesForActivity(A);
const p1 = poles.find((p) => p.label === 'Pole1').key; const p2 = poles.find((p) => p.label === 'Pole2').key;
goals.addCategory(A, 'SecVide', p1); goals.addCategory(A, 'SecPlein', p1);
const secs = goals.secteursForPole(A, p1);
const sVide = secs.find((s) => s.label === 'SecVide').key; const sPlein = secs.find((s) => s.label === 'SecPlein').key;
assert(goals.gridColumnsForPole(A, p1, y).length === 2, 'avant : 2 colonnes');
goals.renameCategory(A, sPlein, 'Renomme');
assert(goals.gridColumnsForPole(A, p1, y).some((c) => c.label === 'Renomme'), 'renommage reflété dans la feuille de route');
goals.planningForActivity(A, sPlein); goals.planningForActivity(A, sVide);
db.prepare("UPDATE goal_periods SET mainGoalText = 'x' WHERE activityId = ? AND category = ?").run(A, sPlein);
const uid = 'u1';
const SP = db.prepare("INSERT INTO sub_projects (activityId, name, createdBy, createdAt, goalCategory) VALUES (?, 'sp', ?, ?, ?)").run(A, uid, now, sPlein).lastInsertRowid;
db.prepare("INSERT INTO sub_project_items (subProjectId, label, done, createdAt) VALUES (?, 'ouverte', 0, ?)").run(SP, now);
const periodsBefore = db.prepare('SELECT COUNT(*) n FROM goal_periods WHERE activityId = ? AND category = ?').get(A, sPlein).n;
goals.removeCategory(A, sVide, {}); goals.removeCategory(A, sPlein, { tasks: 'keep' });
const cols = goals.gridColumnsForPole(A, p1, y).map((c) => c.key);
assert(!cols.includes(sVide), 'secteur supprimé sans contenu : absent de la feuille de route');
assert(!cols.includes(sPlein), 'secteur supprimé avec historique : absent de la feuille de route (année courante)');
assert(cols.length === 1 && cols[0] === p1, 'plus aucun secteur : le pôle sert de colonne');
assert(!goals.gridColumnsForPole(A, p1, y + 1).some((c) => c.key === sPlein), 'année à venir : secteur supprimé absent');
const fut = { currentYear: y + 1 };
const colsPast = goals.gridColumnsForPole(A, p1, y, fut).map((c) => c.key);
assert(colsPast.includes(sPlein), 'année passée : secteur supprimé avec contenu réapparaît');
assert(!colsPast.includes(sVide), 'année passée : secteur supprimé sans contenu reste masqué');
assert(!goals.gridColumnsForPole(A, p1, y + 1, fut).some((c) => c.key === sPlein), 'année courante simulée : secteur supprimé absent');
assert(db.prepare('SELECT COUNT(*) n FROM goal_periods WHERE activityId = ? AND category = ?').get(A, sPlein).n === periodsBefore && db.prepare("SELECT COUNT(*) n FROM goal_periods WHERE activityId = ? AND category = ? AND mainGoalText = 'x'").get(A, sPlein).n === periodsBefore, 'historique conservé en base');
assert(goals.resolveToPole(A, sPlein) === p1, 'statistiques : le secteur supprimé remonte toujours au pôle');
assert(db.prepare('SELECT goalCategory g FROM sub_projects WHERE id = ?').get(SP).g === p1 && db.prepare('SELECT COUNT(*) n FROM sub_project_items WHERE subProjectId = ?').get(SP).n === 1, 'tâche ouverte conservée sous le pôle');
goals.addCategory(A, 'Renomme', p1);
const recre = goals.gridColumnsForPole(A, p1, y);
assert(recre.length === 1 && recre[0].label === 'Renomme' && recre[0].key !== sPlein, 'recréation du même nom : colonne propre, nouvelle clé');
assert(db.prepare("SELECT COUNT(*) n FROM goal_periods WHERE activityId = ? AND category = ? AND mainGoalText != ''").get(A, recre[0].key).n === 0, 'recréation : ancien historique non ressuscité');
assert(goals.gridColumnsForPole(A, p1, y, fut).filter((c) => c.label === 'Renomme').length === 2, 'année passée simulée : ancien et nouveau distincts');
assert(!goals.secteursForPole(A, p1).some((x) => x.key === sPlein || x.key === sVide), 'secteurs supprimés absents de la liste de saisie (Chrono)');
goals.removeCategory(A, p2, { tasks: 'keep' });
const list = goals.categoriesForActivity(A).map((c) => c.key);
assert(list.includes(p1) && !list.includes(p2), 'pôle supprimé absent de la liste du Chrono');
assert(goals.frozenCategoriesForActivity(A).length >= 0, 'historique conservé');
process.exit(failed ? 1 : 0);
